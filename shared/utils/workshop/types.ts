import type { CraftRecipe, RecipeKind } from '../../schemas/recipe'
import type { GameItem } from '../../schemas/item'

/**
 * Single planned crafting operation.
 */
export interface CraftOrder {
  recipeId: string
  times: number
}

/**
 * Standard workshop warning classification codes.
 */
export type WorkshopWarningCode =
  | 'CYCLE_DETECTED'
  | 'MISSING_RECIPE'
  | 'MAX_DEPTH_EXCEEDED'
  | 'CONVERSION_DONOR_DEFICIT'
  | 'UNSUPPORTED_TIER'

/**
 * Structured warning emitted during recipe resolution.
 */
export interface WorkshopWarning {
  code: WorkshopWarningCode
  message: string
  details?: Record<string, unknown>
}

/**
 * Acceptable input shapes for demand specification.
 */
export type DemandInput = Record<string, number> | Array<{ id: string; count: number }>

/**
 * Acceptable input shapes for inventory stock.
 */
export type StockInput = Record<string, number> | Map<string, number>

/**
 * Options controlling workshop demand resolution.
 */
export interface ResolveDemandOptions {
  /**
   * Item tiers permitted to be crafted (e.g. [2, 3, 4, 5]).
   * Items with tiers outside this set are treated as raw deficit.
   * Defaults to [2, 3, 4, 5].
   */
  craftableTiers?: number[]

  /**
   * Whether to utilize existing warehouse stock before crafting.
   * If false, stock is completely ignored (treated as empty).
   * Defaults to true.
   */
  useStock?: boolean

  /**
   * Whether to enable chip reciprocal conversions (e.g. Guard <-> Specialist).
   * Disabled by default to prevent lossy 3:2 conversions unless explicitly requested.
   * Defaults to false.
   */
  allowConversions?: boolean

  /**
   * Whether to calculate expected mathematical values for workshop byproducts.
   * Defaults to false.
   */
  byproducts?: boolean

  /**
   * Maximum recursion or decomposition depth to guard against infinite cycles.
   * Defaults to 15.
   */
  maxDepth?: number

  /**
   * Custom recipes list. Defaults to canonical data/recipes.json.
   */
  recipes?: CraftRecipe[]

  /**
   * Custom items list for tier/rarity resolution. Defaults to data/items.json.
   */
  items?: GameItem[]
}

/**
 * Comprehensive result of workshop demand resolution.
 */
export interface ResolveDemandResult {
  /**
   * Craft operations needed to fulfill demand, ordered execution-ready (bottom-up).
   */
  crafts: CraftOrder[]

  /**
   * Quantities of raw/uncraftable items that must be gathered from stage drops or stores.
   */
  rawDeficit: Record<string, number>

  /**
   * Total Lungmen Dollars (LMD) required to execute all craft operations.
   */
  lmdForCrafting: number

  /**
   * Warehouse inventory remaining after satisfying all demands and crafts,
   * including surplus generated by recipes with resultCount > 1.
   */
  leftoverStock: Record<string, number>

  /**
   * Expected mathematical values (E[count]) of byproducts produced during crafting.
   */
  byproducts: Record<string, number>

  /**
   * Diagnostic warnings generated during graph traversal or recipe execution.
   */
  warnings: WorkshopWarning[]
}

/**
 * Options for configuring a RecipeGraph instance.
 */
export interface RecipeGraphOptions {
  /**
   * Recipe kinds to include. Defaults to ['synthesis', 'manufacture'].
   */
  allowedKinds?: RecipeKind[]

  /**
   * Whether to allow chip conversions. Shorthand for including 'conversion' in allowedKinds.
   */
  allowConversions?: boolean

  /**
   * Maximum path depth during dependency inspection. Defaults to 15.
   */
  maxDepth?: number
}

/**
 * Read-only interface for querying crafting recipes and item dependencies.
 */
export interface RecipeGraph {
  /**
   * Get canonical craft recipe for the given item ID.
   */
  getRecipe(itemId: string): CraftRecipe | undefined

  /**
   * Get all conversion recipes producing the given item ID.
   */
  getConversions(itemId: string): CraftRecipe[]

  /**
   * Retrieve item tier (rarity 1..5) with fallback to default tier 0.
   */
  getItemTier(itemId: string): number

  /**
   * Check whether introducing a dependency from startItemId to targetItemId forms a cycle.
   */
  hasCycle(startItemId: string, targetItemId: string): boolean

  /**
   * Retrieve all registered craft recipes.
   */
  getAllRecipes(): CraftRecipe[]

  /**
   * Return a topological sort of item IDs ordered from products (consumers) to ingredients (dependencies).
   * Guarantees that if item A consumes item B in a crafting recipe, A precedes B in the list.
   */
  getTopologicalOrder(entryItemIds?: Iterable<string>): string[]
}
